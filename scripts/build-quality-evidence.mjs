import {createHash} from 'node:crypto';
import {qualityStats} from '../world/quality-record.js';
import {readFileSync,readdirSync,writeFileSync,existsSync} from 'node:fs';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(import.meta.dirname,'..');
// Fingerprint every served runtime file, including geometry/data, demo and lazy assets.
// Exclude only the two generated evidence files to avoid a hash cycle.
export function qualityDigest(directory=root){
 const files=[];
 const walk=dir=>{for(const entry of readdirSync(resolve(directory,dir),{withFileTypes:true})){
  if(entry.name.startsWith('.'))continue;
  const name=dir+'/'+entry.name;
  if(entry.isDirectory())walk(name);
  else if(!['world/quality-build.js','assets/quality-evidence.json'].includes(name))files.push(name);
 }};
 for(const dir of ['world','assets','demo'])walk(dir);
 for(const entry of readdirSync(directory,{withFileTypes:true}))
  if(entry.isFile()&&(/\.(?:html|css|js|ico)$/.test(entry.name)||entry.name==='.nojekyll'))files.push(entry.name);
 const hash=createHash('sha256');for(const name of files.sort()){
  const bytes=readFileSync(resolve(directory,name));
  const value=/\.(?:html|css|js|mjs|json|svg|txt)$/.test(name)?bytes.toString('utf8').replace(/\r\n/g,'\n'):bytes;
  hash.update(name+'\0').update(value);
 }
 return hash.digest('hex');
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const dir=resolve(process.argv[2]||'validation-artifacts/scene-enhancements-30oct'),baseline=process.argv.includes('--baseline');
 const read=name=>JSON.parse(readFileSync(resolve(dir,name),'utf8').replace(/^\uFEFF/,''));
 const core=read('full-chromium/results.json');
 if(core.length!==20||core.some(s=>s.exitCode!==0))throw Error('All twenty core suites must pass');
 const checks=[{label:'Portfolio browser suites · Chromium',passed:core.length}],objects={};
 for(const engine of ['chromium','webkit']){
  const result=read('after/'+engine+'/results.json');
  if(result.errors.length||!Number.isSafeInteger(result.checks)||result.checks<1)throw Error('Invalid marker results');
  checks.push({label:'Marker assertions · '+(engine==='webkit'?'WebKit':'Chromium'),passed:result.checks});
  for(const item of result.evidence)for(const marker of item.markers){
   const entry=objects[marker.id]||=new Set();entry.add(item.width+'×'+item.height);
  }
  if(!baseline){const value=read('enhancements/'+engine+'/results.json');
   if(value.errors.length||value.sourceDigest!==qualityDigest())throw Error('Enhancement proof does not match this source');
   checks.push({label:'Scene enhancement assertions · '+(engine==='webkit'?'WebKit':'Chromium'),passed:value.checks});}
 }
 const pure=readFileSync(resolve(dir,'pure-final.log'),'utf8'),passed=pure.match(/pass\s+(\d+)/),failed=pure.match(/fail\s+(\d+)/);
 if(!passed||!failed||Number(failed[1]))throw Error('Pure tests must have a clean summary');
 checks.push({label:'Logic tests',passed:Number(passed[1])});
 const evidence={schema:1,recordedAt:new Date().toISOString(),sourceDigest:qualityDigest(),
  scope:baseline?'Marker baseline before scene enhancements':'This source · local browser validation',checks,
  objects:Object.fromEntries(Object.entries(objects).map(([id,sizes])=>[id,{viewports:sizes.size}])),
  exclusions:['Physical iPhone/Android hardware','Production deployment']};
 if(!baseline)qualityStats(evidence,evidence.sourceDigest);
 writeFileSync(resolve(root,'world/quality-build.js'),
  '// Generated by scripts/build-quality-evidence.mjs. Do not edit.\nexport const QUALITY_SOURCE_DIGEST='+
  JSON.stringify(evidence.sourceDigest)+';\n');
 writeFileSync(resolve(root,'assets/quality-evidence.json'),JSON.stringify(evidence,null,2)+'\n');
 console.log('Built public evidence summary from completed local results: '+checks.length+' groups.');
}
