// Development tooling only: point ESBUILD_MODULE at an existing esbuild install.
import {createHash} from 'node:crypto';
import {readFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
const modulePath = process.env.ESBUILD_MODULE;
const {build} = await import(modulePath ? pathToFileURL(modulePath).href : 'esbuild');
const hash=createHash('sha256');
for(const file of ['demo/treadfront/core.js','demo/treadfront/demo.js']) hash.update(readFileSync(file));
const digest=hash.digest('hex');
await build({entryPoints: ['demo/treadfront/demo.js'], bundle: true,
  format: 'iife', platform: 'browser', target: ['es2020'], outfile: 'demo/treadfront/demo.bundle.js',
  banner: {js: `// Generated by scripts/build-treadfront-demo.mjs; only the approved Outer Wall sector.\n// Source SHA-256: ${digest}`}});
