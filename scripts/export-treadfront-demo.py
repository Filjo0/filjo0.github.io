"""Export only the approved first-sector data, retaining the owner's combat engine.
Usage: python scripts/export-treadfront-demo.py <path-to-game-src/core.js>
The original project is read only. No store/native/commerce/save modules are copied.
"""
from pathlib import Path
import sys,re,hashlib,json

def balanced(text,start):
 stack=[];quote=None;line=False;block=False;escape=False;i=start
 pairs={')':'(',']':'[','}':'{'}
 while i<len(text):
  c=text[i];n=text[i+1:i+2]
  if line:
   if c=='\n':line=False
  elif block:
   if c=='*' and n=='/':block=False;i+=1
  elif quote:
   if escape:escape=False
   elif c=='\\':escape=True
   elif c==quote:quote=None
  elif c=='/' and n=='/':line=True;i+=1
  elif c=='/' and n=='*':block=True;i+=1
  elif c in ('"',"'",'`'):quote=c
  elif c in '([{':stack.append(c)
  elif c in ')]}':
   if not stack or stack.pop()!=pairs[c]:raise ValueError('Unbalanced source')
   if not stack:return i+1
  i+=1
 raise ValueError('Unterminated data')

source=Path(sys.argv[1]).read_text(encoding='utf-8');text=source
marker='const levelDefinitions = [';start=text.index(marker)+len(marker)-1;end=balanced(text,start)
first=text.index('{',start);first_end=balanced(text,first);text=text[:start]+'[\n'+text[first:first_end]+'\n]'+text[end:]
for name in ['LABYRINTH_STAGES','LABYRINTH_LEVEL','SAPPER_LEVEL','ESCORT_LEVEL']:
 m=re.search(r'export const '+name+r' = Object.freeze\(',text)
 if not m:raise ValueError('Missing export '+name)
 begin=m.end()-1;end=balanced(text,begin)
 replacement='([])' if name=='LABYRINTH_STAGES' else '({id:"disabled-'+name.lower()+'",base:{},grid:[],waveEntries:[],spawnPoints:[]})'
 text=text[:begin]+replacement+text[end:]
m=re.search(r'export function levelById\(levelId\) \{',text);begin=m.end()-1;end=balanced(text,begin)
text=text[:begin]+'{ if(levelId!=="outer-wall") throw new RangeError("Only the demo sector is available"); return LEVELS[0]; }'+text[end:]
# Shared combat functions remain; optional mode options are stripped at construction.
text=text.replace('export function createLevelState(levelId, options = {}) {','export function createLevelState(levelId, options = {}) {\n  options = {};')
root=Path(__file__).resolve().parents[1];out=root/'demo'/'treadfront';out.mkdir(parents=True,exist_ok=True)
(out/'core.js').write_text('// Generated by scripts/export-treadfront-demo.py. First-sector data only.\n'+text,encoding='utf-8')
(out/'source.json').write_text(json.dumps({'project':'Treadfront','source_file':'src/core.js','source_sha256':hashlib.sha256(source.encode()).hexdigest(),'allowed_sector':'outer-wall','export':'First campaign sector; special-mission maps removed; optional mode options disabled.'},indent=2)+'\n',encoding='utf-8')
print('Exported one sector; original source unchanged.')
